% 需要的合力/力矩 [Fd; Md] 通过分配矩阵 P 的伪逆分配到 n 根绳索的张力上：
%     P = [ I, I, ..., I ; hat(rho_1), hat(rho_2), ..., hat(rho_n) ]   (6 x 3n)
%     [mu_1d; ...; mu_nd] = diag[R0,...,R0] * P' * (P*P')^-1 * [R0'*Fd; Md]
% ★ 可解性条件：rank(P) = 6。P 为 6 x 3n，故必须满足
