            size(cfg.initial.vehicleRpy, 1), size(cfg.initial.vehicleRpy, 2), ...
            cfg.vehicle.count);
    end
    cfg.initial.vehicleR = zeros(3, 3, cfg.vehicle.count);
    for i = 1:cfg.vehicle.count
        cfg.initial.vehicleR(:, :, i) = rpyToRotm(cfg.initial.vehicleRpy(:, i));
    end
